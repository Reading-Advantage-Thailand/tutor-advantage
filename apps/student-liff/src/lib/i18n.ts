type Messages = typeof th;
type DotPrefix<
  TPrefix extends string,
  TKey extends string,
> = `${TPrefix}.${TKey}`;

type MessageKey<T, TPrefix extends string = ""> = {
  [K in keyof T & string]: T[K] extends string
    ? TPrefix extends ""
      ? K
      : DotPrefix<TPrefix, K>
    : MessageKey<T[K], TPrefix extends "" ? K : DotPrefix<TPrefix, K>>;
}[keyof T & string];

export type I18nKey = MessageKey<Messages>;

export function t(key: I18nKey): string {
  const resolved = key.split(".").reduce<unknown>((current, part) => {
    if (current && typeof current === "object" && part in current) {
      return (current as Record<string, unknown>)[part];
    }
    return undefined;
  }, th);
  if (typeof resolved === "string") return resolved;
  return `[missing:${key}]`;
}
